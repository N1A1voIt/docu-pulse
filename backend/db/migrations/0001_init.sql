-- Corrections vs docs/sql-script/scenario-1-db.sql:
--   1. FK directions fixed (child table holds the FK; no more
--      "users.id REFERENCES organizations.id_user" inversions)
--   2. seats is the only membership table (users has no id_organization)
--   3. misspelled organization-id column renamed to id_organization
--   4. organizations.slug widened VARCHAR(5) → VARCHAR(16)
--
-- Creation order avoids FK forward-references:
--   plans → role → users → organizations → seats →
--   possible_integration_docu → integrations
-- All statements idempotent (IF NOT EXISTS); ON DELETE NO ACTION everywhere.

CREATE TABLE IF NOT EXISTS "plans" (
    "id"             INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "plan_name"      VARCHAR(255),
    "price_per_seat" DECIMAL NOT NULL,
    PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "role" (
    "id_role" BIGSERIAL NOT NULL,
    "role"    VARCHAR(255) NOT NULL UNIQUE,
    "slug"    VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY ("id_role")
);

CREATE TABLE IF NOT EXISTS "users" (
    "id"         BIGSERIAL NOT NULL,
    "uuid"       UUID NOT NULL UNIQUE,
    "name"       TEXT NOT NULL,
    "firstname"  TEXT,
    "email"      TEXT NOT NULL UNIQUE,
    "created_at" DATE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "avatar_url" TEXT,
    PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "organizations" (
    "id_organization"   BIGSERIAL NOT NULL,
    "organization_name" TEXT NOT NULL,
    "slug"              VARCHAR(16) NOT NULL UNIQUE,
    "created_at"        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    "is_personal"       BOOLEAN,
    "id_user"           BIGINT NOT NULL,
    "id_plan"           BIGINT NOT NULL,
    PRIMARY KEY ("id_organization"),
    CONSTRAINT "organizations_fk_user" FOREIGN KEY ("id_user")
        REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "organizations_fk_plan" FOREIGN KEY ("id_plan")
        REFERENCES "plans" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "seats" (
    "id_seat"        BIGSERIAL NOT NULL,
    "id_user"        BIGINT NOT NULL,
    "id_organization" BIGINT NOT NULL,
    "id_role"        BIGINT NOT NULL,
    "role_txt"       VARCHAR(255),
    PRIMARY KEY ("id_seat"),
    CONSTRAINT "seats_unique_0" UNIQUE ("id_user", "id_organization"),
    CONSTRAINT "seats_fk_user" FOREIGN KEY ("id_user")
        REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "seats_fk_organization" FOREIGN KEY ("id_organization")
        REFERENCES "organizations" ("id_organization")
        ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "seats_fk_role" FOREIGN KEY ("id_role")
        REFERENCES "role" ("id_role") ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "possible_integration_docu" (
    "id_pi"           BIGSERIAL NOT NULL,
    "integration_name" VARCHAR(255),
    "slug"            VARCHAR(255),
    PRIMARY KEY ("id_pi")
);

CREATE TABLE IF NOT EXISTS "integrations" (
    "id_integration"             BIGSERIAL NOT NULL,
    "id_pi"                      BIGINT NOT NULL,
    "refresh_token"              TEXT,
    "access_token"               TEXT,
    -- false for revoked, true for active
    "status"                     BOOLEAN NOT NULL,
    "id_user_who_clicked_connect" BIGINT,
    "created_at"                 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id_organization"            BIGINT NOT NULL,
    PRIMARY KEY ("id_integration"),
    CONSTRAINT "integrations_fk_pi" FOREIGN KEY ("id_pi")
        REFERENCES "possible_integration_docu" ("id_pi")
        ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "integrations_fk_user" FOREIGN KEY ("id_user_who_clicked_connect")
        REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "integrations_fk_organization" FOREIGN KEY ("id_organization")
        REFERENCES "organizations" ("id_organization")
        ON UPDATE NO ACTION ON DELETE NO ACTION
);

COMMENT ON COLUMN "integrations"."status" IS 'false for revoked true for active';
